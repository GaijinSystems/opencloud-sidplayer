import js from '@eslint/js'
import ts from 'typescript-eslint'
import vue from 'eslint-plugin-vue'
import prettier from 'eslint-config-prettier'
import globals from 'globals'

/**
 * Lint rules.
 *
 * There were none at all until now, which is how a handful of the things the
 * September 2026 review found got in: an unreachable guard, a loop written
 * for its side effect with a `void term` to quiet nobody in particular, a
 * type declared twice in two files, a prop passed to a component that had
 * stopped reading it.
 *
 * `eslint-config-prettier` comes last and turns off everything about layout.
 * This project has a settled style that predates Prettier and nothing here
 * is going to start an argument with it; Prettier is available for new files
 * (`npm run format`) and is not run over the tree.
 *
 * The two files under `public/vendor/sid-engine/` are plain JavaScript that
 * nothing type-checks, and one of them runs in an AudioWorklet, which is not
 * a browser window: it has no `document`, no `fetch` and no `window`, and
 * saying so here is the only place that fact is enforced rather than
 * remembered.
 */
export default ts.config(
  {
    ignores: [
      'dist/**',
      'node_modules/**',
      // Generated by the Module Federation plugin on every build.
      '.__mf__temp/**',
      'engine/build/**',
      'engine/libsidplayfp*/**',
      'e2e/out/**',
      'e2e/node_modules/**'
    ]
  },

  js.configs.recommended,
  ...ts.configs.recommended,
  ...vue.configs['flat/recommended'],

  {
    files: ['**/*.vue'],
    languageOptions: { parserOptions: { parser: ts.parser } }
  },

  /* The app and its tests. */
  {
    files: ['src/**/*.{ts,vue}', 'tests/**/*.ts'],
    languageOptions: {
      globals: { ...globals.browser, ...globals.es2022 }
    },
    rules: {
      // The codebase leans on `_name` for a parameter it must accept and has
      // no use for, which is the convention the type checker uses too.
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_', caughtErrors: 'none' }
      ],
      // `as unknown as Resource` is load-bearing where a synthetic resource
      // is handed to the shell's player, and the shape is documented there.
      '@typescript-eslint/no-explicit-any': 'error',
      'no-console': ['error', { allow: ['info', 'warn', 'error'] }],
      eqeqeq: ['error', 'always', { null: 'ignore' }],
      'prefer-const': 'error',
      'no-var': 'error',
      /*
       * `prefs` is the one shared reactive object in the app: the session
       * owns it, hands the same instance to both transport bars, and watches
       * it to drive the player. Passing it down and writing to it is the
       * design rather than an accident, and `v-model` on a preference is
       * what the panel is.
       */
      'vue/no-mutating-props': 'off',
      // TypeScript already says which props are optional.
      'vue/require-default-prop': 'off',
      // There is one dock and it is called Dock.
      'vue/multi-word-component-names': 'off'
    }
  },

  /* The worklet half of the engine: no DOM, no network. */
  {
    files: ['public/vendor/sid-engine/sid-processor.js'],
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: 'module',
      globals: {
        ...globals.worker,
        sampleRate: 'readonly',
        currentTime: 'readonly',
        currentFrame: 'readonly',
        AudioWorkletProcessor: 'readonly',
        registerProcessor: 'readonly'
      }
    }
  },
  {
    files: ['public/vendor/sid-engine/engine.js'],
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: 'module',
      globals: { ...globals.worker, sampleRate: 'readonly', WebAssembly: 'readonly' }
    },
    rules: {
      /*
       * `const rt = this` in `imports()` is deliberate. The WASI stubs it
       * builds are called by the wasm module, not through the runtime
       * object, so `this` inside them is not what the rule assumes it is.
       */
      '@typescript-eslint/no-this-alias': 'off'
    }
  },

  /*
   * Build and test scripts, which run in Node - except that the bodies of
   * Playwright's `page.evaluate` callbacks are serialised and run inside the
   * browser, so both sets of globals are legitimately in scope in one file.
   */
  {
    files: ['scripts/**/*.mjs', 'e2e/**/*.mjs', '*.config.{js,ts}'],
    languageOptions: {
      globals: { ...globals.node, ...globals.browser }
    },
    rules: {
      'no-console': 'off'
    }
  },

  /*
   * Tests say what they measured, which is the point of the ones that run
   * against the real collection.
   */
  {
    files: ['tests/**/*.ts'],
    rules: { 'no-console': 'off' }
  },

  /*
   * `for (;;)` is the shape every worker loop in this codebase uses, and it
   * is clearer than a `while (true)` that lies about having a condition.
   */
  {
    rules: { 'no-constant-condition': ['error', { checkLoops: false }] }
  },

  prettier
)
