/** Line terminators in a PETSCII string: NUL, or carriage return. */
export const isPetsciiLineEnd = (byte: number): boolean => byte === 0x00 || byte === 0x0d

/**
 * Reads one line starting at `offset`, stopping after its terminator or at the
 * end of the buffer. Returns the text and the offset of the next line. The
 * left-arrow key (0x9D) deletes the previous character, as upstream does; the
 * 32-character cap is upstream's too and matches what the C64 player showed.
 */
export function readPetsciiLine(
  bytes: Uint8Array,
  offset: number,
  maxLength = 32
): { text: string; next: number } {
  let text = ''
  let i = offset
  while (i < bytes.length) {
    const c = bytes[i++]
    if (isPetsciiLineEnd(c)) break
    if (c === 0x9d) {
      if (text.length) text = text.slice(0, -1)
      continue
    }
    const ascii = CHR_TAB[c]
    if (ascii >= 0x20 && text.length < maxLength) text += String.fromCharCode(ascii)
  }
  return { text, next: i }
}
